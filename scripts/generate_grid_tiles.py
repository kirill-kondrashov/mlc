#!/usr/bin/env python3
"""Generate the parallel kernel-check modules of the certified grid.

``Mlc/GridParams.lean`` fixes the classifier parameters. This script asks Lean
for the cost and the unresolved-cell count of every root square, distributes the
expensive squares over independent modules ``Mlc/GridTiles/PartN.lean`` (Lake
builds independent modules in parallel), and writes ``Mlc/GridCertified.lean``,
which combines the per-square equalities into the final bound.
"""

from __future__ import annotations

from pathlib import Path
import argparse
import re
import subprocess

HEAVY_NODES = 8
PART_NODES = 2500


def tile_values(repo: Path) -> list[tuple[int, int, int, int]]:
    proc = subprocess.run(
        ["lake", "env", "lean", "--run", "scripts/grid_tile_values.lean"],
        cwd=repo,
        check=True,
        text=True,
        capture_output=True,
    )
    rows = []
    for line in proc.stdout.splitlines():
        x, y, nodes, cells = (int(v) for v in line.split())
        rows.append((x, y, nodes, cells))
    return rows


def name(x: int, y: int) -> str:
    return f"tile_{'m' if x < 0 else 'p'}{abs(x)}_{y}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[1]
    rows = tile_values(repo)
    heavy = sorted((r for r in rows if r[2] > HEAVY_NODES), key=lambda r: -r[2])
    parts_count = max(1, -(-sum(r[2] for r in heavy) // PART_NODES))
    bins: list[list[tuple[int, int, int, int]]] = [[] for _ in range(parts_count)]
    loads = [0] * parts_count
    for row in heavy:
        k = loads.index(min(loads))
        bins[k].append(row)
        loads[k] += row[2]
    tile_dir = repo / "Mlc" / "GridTiles"
    tile_dir.mkdir(parents=True, exist_ok=True)
    for old in tile_dir.glob("Part*.lean"):
        old.unlink()
    parts = []
    for index, tiles in enumerate(bins):
        if not tiles:
            continue
        body = "\n".join(
            f"set_option maxRecDepth 100000000 in\n"
            f"theorem {name(x, y)} :\n"
            f"    cells gridPmax gridJ gridFuel ⟨{x}, {y}, 3⟩ = {cells} := by\n"
            f"  decide +kernel\n"
            for x, y, _, cells in sorted(tiles)
        )
        (tile_dir / f"Part{index}.lean").write_text(
            "import Mlc.GridCertificate\n"
            "import Mlc.GridParams\n\n"
            "/-!\n"
            "Generated by `scripts/generate_grid_tiles.py`. Each theorem is a\n"
            "kernel-checked equality for one root square of side `1/8`; the modules\n"
            "are independent so that Lake checks them in parallel.\n"
            "-/\n\n"
            "namespace MLC.Certified\n\n" + body + "\nend MLC.Certified\n",
            encoding="utf-8",
        )
        parts.append(index)
    total = sum(r[3] for r in rows)
    heavy_names = ", ".join(name(x, y) for x, y, _, _ in sorted(heavy))
    roots_literal = ", ".join(f"⟨{x}, {y}, 3⟩" for x, y, _, _ in rows)
    imports = "\n".join(f"import Mlc.GridTiles.Part{i}" for i in parts)
    params = (repo / "Mlc" / "GridParams.lean").read_text(encoding="utf-8")
    fuel = int(re.search(r"def gridFuel : Nat := (\d+)", params).group(1))
    (repo / "Mlc" / "GridCertified.lean").write_text(
        f"""import Mlc.GridCertificate
import Mlc.GridParams
{imports}

/-!
# The checked grid bound

The classifier of `Mlc.GridCertificate` is evaluated by kernel reduction on the
dyadic grid over the upper half of the box `[-2, 2]²`: the 128 root squares of
side `1/8`, each subdivided `gridFuel` further times. The expensive squares are
checked in the generated modules `Mlc.GridTiles.Part*` (see
`scripts/generate_grid_tiles.py`); the remaining squares are evaluated here.
The theorem below is an unconditional upper bound for the area of the set of
parameters of `M` that are not interior points.
-/

namespace MLC.Certified

open MeasureTheory

/-- Number of unresolved finest cells of the upper half at depth `gridDepth`. -/
def gridCells : ℕ := {total}

/-- The root squares as an explicit list, so that the sum can be expanded. -/
theorem rootsUp_eq : rootsUp = [{roots_literal}] := by
  decide +kernel

set_option maxRecDepth 100000000 in
theorem gridCells_eq : rootCellsUp gridPmax gridJ gridFuel = gridCells := by
  rw [rootCellsUp, rootsUp_eq]
  simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil,
    {heavy_names}]
  decide +kernel

/-- The certified area bound for the non-interior part of the Mandelbrot set. -/
theorem unresolved_volume_le_grid :
    volume Unresolved ≤ ENNReal.ofReal (2 * (gridCells : ℝ) / 4 ^ gridDepth) := by
  have h := unresolved_volume_le_sym gridPmax gridJ gridFuel
  rw [gridCells_eq] at h
  have e : 2 * ENNReal.ofReal ((gridCells : ℝ) / 4 ^ (3 + gridFuel)) =
      ENNReal.ofReal (2 * (gridCells : ℝ) / 4 ^ gridDepth) := by
    rw [← ENNReal.ofReal_ofNat 2, ← ENNReal.ofReal_mul (by norm_num), gridDepth]
    congr 1
    ring
  rwa [e] at h

end MLC.Certified
""",
        encoding="utf-8",
    )
    print(
        f"{len(heavy)} heavy tiles in {len(parts)} modules; "
        f"max load {max(loads)} of {sum(loads)} nodes; cells {total}; fuel {fuel}"
    )


if __name__ == "__main__":
    main()
